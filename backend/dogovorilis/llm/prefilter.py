"""Предфильтр перед LLM: дешёво отсекает сообщения, в которых точно нет договорённости.

Цель — не терять договорённости (recall ≥ 0,95), а пропускать в модель как можно меньше.
Правила ловят признаки обещания, просьбы, согласия и срока; короткое согласие («+», «ок»)
пропускаем, только если в недавнем контексте была просьба или вопрос «кто сделает».
"""

import re
from dataclasses import dataclass

_W = r"(?<![а-яё])"  # граница слова для кириллицы

PROMISE = re.compile(_W + r"(сдела\w*|додела\w*|переде\w*|запил\w*|допил\w*|скин\w*|закин\w*|подкин\w*|"
                     r"напиш\w*|допиш\w*|подготов\w*|возьм\w*|бер(у|усь)|займ(усь|у)|гляну|глянем|посмотр(ю|им)|"
                     r"чекну|проверю|соберу|оформлю|пофикш\w*|почин\w*|зарелиз\w*|задепло\w*|запуш\w*|смерж\w*|"
                     r"отправлю|подгоню|добь\w*|нарису\w*|сверста\w*|протест\w*|потест\w*|разбер(усь|у)|залью|"
                     r"выложу|найду|куплю|принесу|распечата\w*|запишу|организу\w*|позвоню|спрошу|узнаю|"
                     r"подтяну|наберу|договорюсь|созвонюсь|накидаю|набросаю|прикручу|допишу|перепишу|"
                     r"доведу|закончу|допрошу|оформлю|сниму|смонтирую|опубликую|выгружу|обновлю|поправлю|"
                     r"исправлю|заведу|добавлю|выпущу|выкачу|запущу|настрою|подготовлю|пришлю|покажу|передам|расскажу|"
                     r"допилим|сделаем|возьмем|возьмём|на мне|давай я|го я|я могу|могу|я в деле|"
                     r"я сам|сам сделаю|беру на себя|за мной|я гляну|я займусь|берусь|я разберусь|сдам|сдаю|кину|"
                     r"апрувну|подниму|разверну|согласую|посчитаю|подпишу|закажу|оплачу)|"
                     r"\bi(?:'ll| will| am going to|'m going to)\b")
REQUEST = re.compile(_W + r"(сделай\w*|возьми\w*|займись|глянь\w*|посмотри\w*|скинь\w*|напиши\w*|подготовь\w*|"
                     r"сможешь|можешь|сделаешь|возьмешь|возьмёшь|глянешь|скинешь|на тебе|на вас|кто (сделает|возьмет|"
                     r"возьмёт|может|готов|займется|займётся|сможет)|кто-нибудь|кто нибудь|нужен кто|"
                     r"поручаю|назначаю|ответственн\w*|бери|берите|забирай|забери)|@\w+")
ACCEPT = re.compile(r"^\s*(\+|\+\+|ок\w*|окей|оке|okay|ok|ага|угу|да\w*|лан\w*|ладно|го|изи|норм\w*|без проблем|"
                    r"принято|хорошо|договорились|понял\w*|сделаю|беру|я|сойдет|сойдёт|конечно|канеш\w*|"
                    r"пойдет|пойдёт|можно|давай|👍|✅|🫡|💪)", re.IGNORECASE)
TIME = re.compile(_W + r"(сегодня|седня|сёдня|завтр\w*|послезавтр\w*|вечер\w*|ночи|утр\w*|выходн\w*|выхах|выхи|"
                  r"недел\w*|пн|вт|ср|чт|пт|сб|вс|понедельник\w*|вторник\w*|сред[уы]|четверг\w*|пятниц\w*|"
                  r"суббот\w*|воскресень\w*|кт|чекпоинт\w*|защит\w*|дедлайн\w*|ща|щас|сейчас|через|"
                  r"к \d|до \d|\d{1,2}[./]\d{1,2})")


# поручение строкой «задача - имя»: «развернуть сайт - андрей», «сделать презу к пд — Сема»
DASH_ASSIGN = re.compile(r"^\s*(?P<task>[^\n]{3,100}?)\s+[-—–]\s+@?(?P<who>[a-zа-яё]{2,20})\s*[.!]?\s*$",
                         re.IGNORECASE | re.MULTILINE)


@dataclass
class PrefilterResult:
    passed: bool
    reasons: list[str]


def prefilter(text: str, context: list[str] | None = None) -> PrefilterResult:
    t = (text or "").lower().replace("ё", "е")
    reasons = []
    if PROMISE.search(t):
        reasons.append("promise")
    if REQUEST.search(t):
        reasons.append("request")
    if DASH_ASSIGN.search(t):
        reasons.append("assign")
    if TIME.search(t) and len(t) < 400:
        reasons.append("time")
    if ACCEPT.search(t) and len(t) < 80:
        recent = " ".join(c.lower() for c in (context or [])[-6:])
        if REQUEST.search(recent) or "?" in recent:
            reasons.append("accept_after_request")
    return PrefilterResult(passed=bool(reasons), reasons=reasons)
