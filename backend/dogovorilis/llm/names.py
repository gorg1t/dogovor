def _norm(s: str) -> str:
    s = (s or "").strip().lstrip("@").lower().replace("ё", "е")
    s = re.split(r"[\s_.\-0-9]+", s)[0] if s else s  # первое слово / начало ника до «_» и цифр
    if re.fullmatch(r"[a-z]+", s):
        for lat, cyr in _TRANSLIT:
            s = s.replace(lat, cyr)
    return s


_FORMS = [[_norm(w) for w in g.split()] for g in _GROUPS]


def same_name(a: str, b: str) -> bool:
    """Одно имя в разных падежах: «Лёша»/«Лёше»/«Лёшу», «Алексей»/«Алексею». Сравниваем общее начало слова."""
    a, b = _norm(a), _norm(b)
    if len(a) < 2 or len(b) < 2:
        return False
    common = len(next((a[:i] for i in range(min(len(a), len(b)), 0, -1) if a[:i] == b[:i]), ""))
    return a == b or common >= max(3, min(len(a), len(b)) - 2)


def _group(name: str) -> list[str] | None:
    """Формы имени: «Лёша»/«Лёше» → алексей, леша, леха, …. Сначала точная форма, потом падеж; спорное — None."""
    n = _norm(name)
    exact = [g for g in _FORMS if n in g]
    if exact:
        return exact[0]
    fuzzy = [g for g in _FORMS if any(same_name(n, f) for f in g)]
    return fuzzy[0] if len(fuzzy) == 1 else None


def member_names(m: dict) -> list[str]:
    return [x for x in (m.get("name"), m.get("username"), m.get("alias")) if x]


def find_member(name: str | None, members: list[dict]) -> dict | None:
    """Участник, которого назвали по имени; None — если не нашли или подходят несколько."""
    n = _norm(name or "")
    if len(n) < 2:
        return None

    def one(cands: list[dict]) -> dict | None:
        return cands[0] if len({m.get("user_id") or m["name"] for m in cands}) == 1 else None

    exact = [m for m in members if any(_norm(x) == n for x in member_names(m))]
    if exact:
        return one(exact)
    group = _group(name)
    in_group = [m for m in members if group and any(_norm(x) in group for x in member_names(m))]
    if in_group:
        return one(in_group)
    declined = [m for m in members if any(same_name(x, name) for x in member_names(m))]  # «Егору» → Егор
    return one(declined) if declined else None
